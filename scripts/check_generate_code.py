# Runs scripts/generate_code.py and fails if the committed tree is not exactly
# what it generates. `git diff` alone only sees tracked files that come out
# different, so two more checks cover what it cannot:
#
# - Orphans: a tracked file whose header says flatc wrote it, but which
#   generate_code.py did not write. Nothing regenerates it, so it can go stale
#   without the diff ever changing.
# - Untracked outputs: a file generate_code.py wrote that git does not track.
#   It never reaches a commit, and `git diff` does not look at it.
#
# "Wrote" is judged by modification time: a file counts as written if its
# mtime changed while generate_code.py ran, or if generate_code.py reported it
# as one it regenerated but left untouched because nothing changed.

import fnmatch
import os
from pathlib import Path
import platform
import re
import subprocess
import sys
import tempfile
import time

# Get the path where this script is located so we can invoke the script from
# any directory and have the paths work correctly.
script_path = Path(__file__).parent.resolve()

# Get the root path as an absolute path, so all derived paths are absolute.
root_path = script_path.parent.absolute()

EXCLUSIONS = "scripts/check_generate_code_exclusions.txt"

# Header lines that mark a file as generator output, matched case-insensitively
# within the first HEADER_BYTES of each tracked file. Each is emitted by the
# generator named above it. The gate fails if one no longer occurs in any other
# tracked file, so the list cannot keep a dead entry.
MARKERS = [
    # code_generators.cpp (most languages), bfbs_gen_lua.cpp, bfbs_gen_nim.cpp,
    # idl_gen_rust.cpp (module root file).
    "automatically generated by the FlatBuffers compiler",
    # idl_gen_go.cpp
    "Code generated by the FlatBuffers compiler. DO NOT EDIT.",
    # idl_gen_fbs.cpp (--proto)
    "// Generated from ",
    # grpc/src/compiler/cpp_generator.cc
    "Generated by the gRPC C++ plugin.",
    # grpc/src/compiler/go_generator.cc
    "Generated by gRPC Go plugin",
    # grpc/src/compiler/java_generator.cc
    "Generated by flatc compiler (version",
    # grpc/src/compiler/python_generator.cc
    "Generated by the gRPC FlatBuffers compiler",
    # grpc/src/compiler/ts_generator.cc, idl_gen_grpc.cpp (Swift)
    "Generated GRPC code for FlatBuffers",
]

# Generated files carry their marker within the first 50 bytes. Generator
# sources carry the same text deeper in, inside string literals (the earliest
# is past byte 1500), so this bound tells the two apart.
HEADER_BYTES = 512

# Environment variable naming a file that generate_code.py appends to for each
# output it accounts for without writing it this run.
UNWRITTEN_ENV = "FLATBUFFERS_REGEN_UNWRITTEN"


def git(*arguments):
  return subprocess.run(
      ["git"] + list(arguments),
      cwd=root_path,
      check=True,
      stdout=subprocess.PIPE,
  ).stdout.decode("utf-8")


def git_ok(*arguments):
  return (
      subprocess.run(["git"] + list(arguments), cwd=root_path).returncode == 0
  )


def git_paths(*arguments):
  # -z output: paths are '/'-separated and never quoted, on every platform.
  return [p for p in git(*arguments, "-z").split("\0") if p]


def mtime(path):
  try:
    return os.stat(Path(root_path, path)).st_mtime_ns
  except FileNotFoundError:
    return None


def has_marker(path):
  full = Path(root_path, path)
  if full.is_symlink() or not full.is_file():
    return False
  with open(full, "rb") as f:
    head = f.read(HEADER_BYTES).decode("utf-8", "replace").lower()
  return any(marker.lower() in head for marker in MARKERS)


def load_exclusions():
  """Return the exclusion list's patterns, and any format errors.

  Groups are separated by blank lines. Each group's '#' lines are its reason
  and its other lines are path patterns.
  """
  all_patterns, errors = [], []
  text = Path(root_path, EXCLUSIONS).read_text(encoding="utf-8")
  for block in re.split(r"\n[ \t\r]*\n", text):
    lines = [line.strip() for line in block.split("\n") if line.strip()]
    patterns = [line for line in lines if not line.startswith("#")]
    if patterns and len(patterns) == len(lines):
      errors.append(
          f"{EXCLUSIONS}: no '#' reason above {patterns[0]!r}; say what "
          "produces these files and why generate_code.py does not."
      )
    all_patterns += patterns
  return all_patterns, errors


def wait_for_clock_tick():
  """Return once the filesystem clock has moved on.

  A file written after that cannot keep the mtime it had in the snapshot, even
  on filesystems that store mtimes in whole seconds.
  """
  probe = Path(
      root_path,
      git("rev-parse", "--git-path", "check_generate_code.probe").strip(),
  )
  try:
    probe.write_bytes(b"0")
    first = os.stat(probe).st_mtime_ns
    deadline = time.monotonic() + 5
    while os.stat(probe).st_mtime_ns == first and time.monotonic() < deadline:
      time.sleep(0.01)
      probe.write_bytes(b"0")
    probe.unlink()
  except OSError as err:
    print(f"NOTE: could not probe the filesystem clock ({err}); continuing.")


def error_block(lines):
  print("\nERROR: " + "\nERROR: ".join(lines))


def report(title_lines, paths):
  """Print the error and its paths, if there are any; return whether so."""
  if paths:
    error_block(title_lines)
    for path in paths:
      print(f"  {path}")
  return bool(paths)


if not git_ok("diff", "--quiet", "--ignore-cr-at-eol"):
  print(
      "\n"
      "ERROR: **********************************************************\n"
      "ERROR: * The following differences were found after building.   *\n"
      "ERROR: * Perhaps there is a difference in the flags for the.    *\n"
      "ERROR: * CMakeLists.txt vs the scripts/generate_code.py script? *\n"
      "ERROR: **********************************************************\n"
  )
  subprocess.run(["git", "diff", "--binary", "--exit-code"], cwd=root_path)
  sys.exit(1)

exclusion_patterns, exclusion_errors = load_exclusions()
if exclusion_errors:
  error_block(exclusion_errors)
  sys.exit(1)

# Every marker any tracked file but this one contains, in one pass. Exit
# status 1 only means no match, so it is not checked.
grep = ["git", "grep", "-h", "-o", "-a", "-i", "-F"]
for marker in MARKERS:
  grep += ["-e", marker]
grep += ["--", ".", ":(exclude)scripts/check_generate_code.py"]
found = subprocess.run(grep, cwd=root_path, stdout=subprocess.PIPE).stdout
found = set(found.decode("utf-8", "replace").lower().splitlines())
if report(
    [
        "These header markers in scripts/check_generate_code.py match no",
        "tracked file. Remove them, or correct them if a generator changed",
        "its header:",
    ],
    [marker for marker in MARKERS if marker.lower() not in found],
):
  sys.exit(1)

# Snapshot before generating: which tracked files claim to be generated, and
# the mtimes of those and of every untracked file.
generated = [p for p in git_paths("ls-files") if has_marker(p)]
untracked_before = git_paths("ls-files", "--others", "--exclude-standard")
mtimes_before = {p: mtime(p) for p in generated + untracked_before}

excluded = {
    pattern: [p for p in generated if fnmatch.fnmatchcase(p, pattern)]
    for pattern in exclusion_patterns
}
excluded_paths = {p for paths in excluded.values() for p in paths}

wait_for_clock_tick()

# Run the generate_code.py script, forwarding arguments
gen_cmd = ["scripts/generate_code.py"] + sys.argv[1:]
if platform.system() == "Windows":
  gen_cmd = ["py"] + gen_cmd
with tempfile.TemporaryDirectory() as tmp:
  unwritten_log = Path(tmp, "unwritten")
  unwritten_log.touch()
  gen_result = subprocess.run(
      gen_cmd,
      cwd=root_path,
      env=dict(os.environ, **{UNWRITTEN_ENV: str(unwritten_log)}),
  )
  unwritten = set(unwritten_log.read_text(encoding="utf-8").splitlines())

# A generator that fails part-way leaves every file it never reached as it
# was, so the diff below can come back clean on a broken generator. Its exit
# status has to count on its own.
if gen_result.returncode != 0:
  print(
      "\n"
      "ERROR: scripts/generate_code.py exited with status "
      f"{gen_result.returncode}; see its output above.\n"
  )
  sys.exit(gen_result.returncode)


def written(path):
  return mtime(path) != mtimes_before.get(path) or path in unwritten


failed = False

if not git_ok("diff", "--quiet", "--ignore-cr-at-eol"):
  failed = True
  print(
      "\n"
      "ERROR: *********************************************************\n"
      "ERROR: * The following differences were found after running    *\n"
      "ERROR: * the scripts/generate_code.py script. Maybe you forgot *\n"
      "ERROR: * to run it after making changes in a generator?        *\n"
      "ERROR: *********************************************************\n"
  )
  subprocess.run(["git", "diff", "--binary", "--exit-code"], cwd=root_path)

orphans = [p for p in generated if p not in excluded_paths and not written(p)]
failed |= report(
    [
        "These tracked files have a generated-code header, but",
        "scripts/generate_code.py did not write them, so nothing keeps",
        "them current. Delete each one, or add the command that produces",
        "it to generate_code.py. If another script produces it, list it in",
        f"{EXCLUSIONS} with the reason.",
    ],
    orphans,
)

failed |= report(
    [
        f"These patterns in {EXCLUSIONS} match no tracked file",
        "with a generated-code header. Remove them:",
    ],
    [pattern for pattern, paths in excluded.items() if not paths],
)

failed |= report(
    [
        "scripts/generate_code.py now writes every file these patterns in",
        f"{EXCLUSIONS} match. Remove them:",
    ],
    [
        pattern
        for pattern, paths in excluded.items()
        if paths and all(written(p) for p in paths)
    ],
)

failed |= report(
    [
        "scripts/generate_code.py wrote these files, which git does not",
        "track. Commit them, or stop generating them:",
    ],
    [
        p
        for p in git_paths("ls-files", "--others", "--exclude-standard")
        if written(p)
    ],
)

sys.exit(1 if failed else 0)
